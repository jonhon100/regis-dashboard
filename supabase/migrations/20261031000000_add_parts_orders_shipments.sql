-- REGIS HUB development: Parts Orders / Shipments workflow
-- Development project only. Designed for authenticated-user RLS.

create table if not exists public.regis_suppliers (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  name text not null check (char_length(trim(name)) between 1 and 200),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists regis_suppliers_user_name_ci
  on public.regis_suppliers (user_id, lower(name));

create table if not exists public.regis_parts_orders (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  boat_name text not null check (char_length(trim(boat_name)) between 1 and 200),
  captain_name text,
  flag text,
  next_port text,
  supplier_id bigint references public.regis_suppliers(id) on delete set null,
  supplier_name text not null check (char_length(trim(supplier_name)) between 1 and 200),
  purchase_order_number text,
  notes text,
  order_date date not null default current_date,
  courier text,
  tracking_number text,
  tracking_url text,
  shipment_status text not null default 'awaiting_shipment'
    check (shipment_status in ('awaiting_shipment','shipped','broker_prealerted','delivered')),
  shipment_date date,
  broker_prealerted_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists regis_parts_orders_user_created
  on public.regis_parts_orders (user_id, created_at desc);
create index if not exists regis_parts_orders_user_status
  on public.regis_parts_orders (user_id, shipment_status);

create table if not exists public.regis_settings (
  user_id uuid primary key default auth.uid() references auth.users(id) on delete cascade,
  broker_email_subject_template text not null default 'Incoming Shipment - {boat_name}',
  broker_email_body_template text not null default E'Please see details of the incoming shipment:\n\nVessel: {boat_name}\nCaptain: {captain}\nFlag: {flag}\nNext Port: {next_port}\nCourier: {courier}\nTracking: {tracking_number}\nPO: {po_number}\n\nRegards,\nRegis Electronics',
  updated_at timestamptz not null default now()
);

alter table public.regis_suppliers enable row level security;
alter table public.regis_parts_orders enable row level security;
alter table public.regis_settings enable row level security;

drop policy if exists "regis_suppliers_owner_all" on public.regis_suppliers;
create policy "regis_suppliers_owner_all" on public.regis_suppliers
  for all to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());

drop policy if exists "regis_parts_orders_owner_all" on public.regis_parts_orders;
create policy "regis_parts_orders_owner_all" on public.regis_parts_orders
  for all to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());

drop policy if exists "regis_settings_owner_all" on public.regis_settings;
create policy "regis_settings_owner_all" on public.regis_settings
  for all to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());

grant select, insert, update, delete on public.regis_suppliers to authenticated;
grant select, insert, update, delete on public.regis_parts_orders to authenticated;
grant select, insert, update, delete on public.regis_settings to authenticated;
grant usage, select on sequence public.regis_suppliers_id_seq to authenticated;
grant usage, select on sequence public.regis_parts_orders_id_seq to authenticated;
